import { cp, mkdir, readFile, readdir, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const platforms = ['windows', 'linux', 'macOS', 'iphone', 'android'];
const args = process.argv.slice(2);
const selected = args.includes('--platform') ? [args[args.indexOf('--platform') + 1]] : platforms;
const artifact = args.includes('--artifact') ? args[args.indexOf('--artifact') + 1] : null;
if (selected.some((platform) => !platforms.includes(platform))) throw new Error('Unknown platform.');
const exists = async (filename) => access(filename).then(() => true, () => false);
const packageInfo = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const sources = ['src', 'shared', 'public', 'desktop', 'scripts', 'tests', 'docs', '.github', '.gitignore', '.gitattributes', 'android/sourcecode/native', 'iphone/sourcecode/native', 'package.json', 'package-lock.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml', 'tsconfig.json', 'tsconfig.app.json', 'tsconfig.node.json', 'vite.config.ts', 'vitest.config.ts', 'playwright.config.ts', 'index.html', 'capacitor.config.ts', 'electron-builder.yml', 'README.md', 'LICENSE', 'AGENTS.md'];
const sourceCaches = new Set(['node_modules', '.git', '.gradle', 'build', 'Pods', 'DerivedData', '.swiftpm', 'xcuserdata']);

async function copyIfExists(source, destination) {
  if (await exists(source)) await cp(source, destination, {
    recursive: true,
    force: true,
    filter: (filename) => !path.relative(source, filename).split(path.sep).some((part) => sourceCaches.has(part)),
  });
}

async function findAssets(folder) {
  for (const candidate of [`shared/application/${folder}`, `public/${folder}`, `dist/${folder}`]) {
    if (await exists(path.join(root, candidate))) return path.join(root, candidate);
  }
  throw new Error(`Missing canonical ${folder} directory.`);
}

for (const platform of selected) {
  const destination = path.join(root, platform);
  const application = path.join(destination, 'application');
  await Promise.all(['application', 'application/configs', 'application/lang', 'sourcecode', 'codex'].map((folder) => mkdir(path.join(destination, folder), { recursive: true })));
  await cp(await findAssets('configs'), path.join(application, 'configs'), { recursive: true, force: true });
  await cp(await findAssets('lang'), path.join(application, 'lang'), { recursive: true, force: true });
  await copyIfExists(path.join(root, 'dist'), path.join(application, 'web'));
  for (const source of sources) await copyIfExists(path.join(root, source), path.join(destination, 'sourcecode', source));
  await copyIfExists(path.join(root, 'codex'), path.join(destination, 'codex'));
  await writeFile(path.join(destination, 'codex', 'PLATFORM.md'), `# ${platform}\n\nGenerated with \`node scripts/stage-platforms.mjs --platform ${platform}\`.\nThe root source is canonical. Rebuild it before staging. Native mobile projects live in this platform's sourcecode/native directory.\nDo not put credentials, signing certificates or personal data here.\n`);

  const desktopMarker = { windows: '-windows-', linux: '-linux-', macOS: '-mac-' }[platform];
  if (desktopMarker && await exists(path.join(root, 'build', 'desktop'))) {
    for (const filename of await readdir(path.join(root, 'build', 'desktop'))) {
      if (filename.includes(desktopMarker) && /\.(exe|AppImage|tar\.gz|dmg|zip)$/.test(filename)) {
        await cp(path.join(root, 'build', 'desktop', filename), path.join(application, filename));
      }
    }
  }
  if (artifact) {
    const source = path.resolve(root, artifact);
    if (!await exists(source)) throw new Error(`Artifact does not exist: ${artifact}`);
    let filename = path.basename(source);
    if (platform === 'android' && filename === 'app-debug.apk') filename = `Stratagem-Trainer-${packageInfo.version}-android-debug.apk`;
    await cp(source, path.join(application, filename), { recursive: true, force: true });
  }
  await writeFile(path.join(application, 'README.txt'), `Stratagem Trainer ${packageInfo.version} — ${platform}\n\nconfigs/ and lang/ contain editable JSON source files. Runtime copies are bundled in the executable. Import changed configs in the app, or rebuild to replace bundled defaults.\nweb/ is the offline-capable web version; serve it over HTTP(S), rather than opening index.html as a local file.\nNative artifacts are generated by GitHub Actions on the corresponding operating system.\n${platform === 'iphone' ? 'Simulator .app and unsigned .ipa are development artifacts. An unsigned .ipa cannot be installed on a normal iPhone. Use the web version in Safari (Share > Add to Home Screen), or build/sign with your Apple developer identity.\n' : ''}${platform === 'macOS' ? 'macOS builds are unsigned until a developer identity is configured. Gatekeeper may require manual approval in Privacy & Security.\n' : ''}${platform === 'android' ? 'The debug APK is installable for testing. It uses the Android debug signing key, rather than a Play Store release identity.\n' : ''}`);
  const checksums = [];
  for (const filename of (await readdir(application)).sort()) {
    if (/\.(exe|AppImage|tar\.gz|dmg|zip|apk|ipa)$/.test(filename)) {
      checksums.push(`${createHash('sha256').update(await readFile(path.join(application, filename))).digest('hex')}  ${filename}`);
    }
  }
  await writeFile(path.join(application, 'SHA256SUMS.txt'), checksums.join('\n') + (checksums.length ? '\n' : ''));
  console.log(`Staged ${platform}/application, sourcecode and codex (${checksums.length} native artifacts).`);
}
